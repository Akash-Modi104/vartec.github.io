<div class="page-head"><div><h1>Help</h1><p>How to do the common jobs. Nothing you do here reaches the live website until you press Publish.</p></div></div>
<section class="card help">
  <h2>How editing works</h2>
  <ol>
    <li><strong>Edit.</strong> Change a page and press <em>Save draft</em>. Visitors still see the old version.</li>
    <li><strong>Preview.</strong> Press <em>Preview</em> at the top to see the website with your changes. Only signed-in editors can see a preview.</li>
    <li><strong>Publish.</strong> Press <em>Publish to website</em>. Your changes are live at once.</li>
  </ol>
  <p>Changed your mind before publishing? On the Dashboard, press <em>Discard changes</em>. Published something by mistake? Go to Settings, <em>Earlier versions</em>, and restore the version you want.</p>
</section>
<section class="card help">
  <h2>Change the wording on a service or project</h2>
  <ol><li>Open <em>Services</em> or <em>Projects</em> and choose the page.</li><li>Edit the title, introduction or any section. A section is a heading, some text and an optional picture.</li><li>Use <em>Add bullet point</em> or <em>Add paragraph</em> inside a section for lists and extra text.</li><li>Use the arrows to move sections or points up and down, and the bin to remove them.</li><li>Press <em>Save draft</em>, then Preview, then Publish.</li></ol>
</section>
<section class="card help">
  <h2>Add a new project</h2>
  <ol><li>Open <em>Projects</em> and press <em>Add a project</em>.</li><li>Give it a title, an introduction and a card picture. The card picture is what shows on the home page.</li><li>Add one section for each thing you want to show.</li><li>Save, preview and publish. The project appears in the menu and on the home page automatically.</li></ol>
  <p>To hide a page without deleting it, switch off <em>Shown on website</em>.</p>
</section>
<section class="card help">
  <h2>Add or change a picture</h2>
  <ol><li>Wherever a picture can go, press <em>Choose image</em>.</li><li>Pick one from the library, or upload a new one in the same window.</li><li>When you upload, say what it shows, where it came from and whether you have the right to use it.</li></ol>
  <p><strong>Only use pictures you took yourself or hold a licence for.</strong> Pictures copied from Google, news sites or stock libraries without paying can lead to a copyright claim. The admin marks any picture with no licence on record so you can replace it.</p>
</section>
<section class="card help">
  <h2>Enquiries</h2>
  <p>Messages from the contact form are emailed as before, and a copy is kept under <em>Enquiries</em>. Mark each one as done when you have dealt with it. Deleting an enquiry here does not delete the email.</p>
</section>
<section class="card help">
  <h2>Search engines</h2>
  <p>Each page has a <em>Search engines and web address</em> box. The title should say what the page offers and where, in about 60 characters. The description should be one or two plain sentences, about 155 characters. Leave both empty to use the page title and introduction.</p>
</section>
